const DICTS = { en, es };

// Picks 'en' or 'es' from a project setting and a Jira locale such as "es_ES" or "en-US".
export function pickLang(setting, locale) {
  if (setting === 'en' || setting === 'es') return setting;
  return /^es/i.test(locale || '') ? 'es' : 'en';
}

export function t(lang, key, params) {
  const dict = DICTS[lang] || en;
  let s = dict[key] !== undefined ? dict[key] : en[key] !== undefined ? en[key] : key;
  if (params) {
    s = s.replace(/\{(\w+)\}/g, (m, k) => {
      const v = params[k];
      if (v === undefined || v === null) return m;
      return Array.isArray(v) ? v.map((x) => `“${x}”`).join(', ') : String(v);
    });
  }
  return s;
}

// Hint shown under a failed check.
export function failHint(lang, check) {
  const p = check.params || {};
  switch (check.id) {
    case 'storyFormat': return t(lang, `check.storyFormat.fail.${p.missing === 'benefit' ? 'benefit' : 'all'}`);
    case 'gherkin': return p.count ? t(lang, 'check.gherkin.fail.incomplete', p) : t(lang, 'check.gherkin.fail.none');
    default: return t(lang, `check.${check.id}.fail`, p);
  }
}

